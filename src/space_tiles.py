"""Space tiles: Herdr's `spaces` and `picker` mods with a logo or an accent tile per space.

Herdr draws each space as a colored tile with the first letter of its name, so
every "acme · ..." space shows A. This module makes `ormus-spaces` and
`ormus-picker` from Herdr's own mods (the copies in your Herdr home) with a few
anchored edits: a logo where the config sets one, else a brand accent tile with
the letter that follows the separator ("acme · WEB" shows W). Each edit asserts
its anchor, so a Herdr update that moves the code stops the install instead of
writing a broken mod. It also writes the same tiles for the Flock sidebar
(`mods/ormus-needs/tiles.js`).

Standard library only. The logo files are used as they are (SVG or PNG): the
tile draws them at 18 px on an optional background color.
"""

from __future__ import annotations

import json
from collections.abc import Callable

TILE_ON_ACCENT = "#0e1830"  # the text color on an accent tile: the brand's deep midnight
# The brand's identity accents. A space color of Herdr's (an ANSI name) is moved to one of these.
ACCENTS = {
    "rose": "#e0849a",
    "teal": "#4fbcae",
    "leaf": "#86c272",
    "ember": "#e8955f",
    "sky": "#78a6ee",
    "iris": "#ad92e6",
}
# Herdr stores a space's color as an ANSI name; these are the same hues as its
# MARK table, moved to the brand accents.
MARK_TO_ACCENT = {
    "ansi6": "teal",
    "ansi3": "ember",
    "ansi4": "sky",
    "ansi5": "iris",
    "ansi2": "leaf",
    "ansi1": "rose",
}
UPSTREAM_MARK = (
    'const MARK = { ansi6: "#22a99a", ansi3: "#e3814f", ansi4: "#5b8def", '
    'ansi5: "#8b7cf6", ansi2: "#3fae6a", ansi1: "#d9649a" };'
)
GPUI_IMPORT = 'import { View, div, svg } from "gpui-kit";'
GPUI_IMPORT_IMAGE = 'import { View, div, svg, image } from "gpui-kit";'
SPACES_TILE = (
    ".when(!tree, el => el.child(h_flex().size(18).flex_none().rounded(5).bg(fill)"
    '.items_center().justify_center().text_size(10.5).font_bold().text_color("#ffffff")'
    '.child([...w.name][0]?.toUpperCase() ?? "?")))'
)
PICKER_TILE = (
    ".child(h_flex().size(18).rounded(5).bg(spaceColor(t, r.w)).items_center()"
    '.justify_center().text_size(10.5).font_bold().text_color("#ffffff")'
    '.child([...r.w.name][0]?.toUpperCase() ?? "?"))'
)

TILE_JS = """
// Ormus look (playbook-herdr-ormus-look, generated by src/space_tiles.py from spaces.json: edit that file, not this).
// A space shows its logo where spaces.json sets one, else an accent tile with its workspace's
// letter: "acme · WEB" shows W, not the A of every acme space.
const ORMUS_SPACES = __TABLE__;
const ORMUS_ACCENTS = __ACCENTS__;
const ORMUS_SEPARATOR = __SEPARATOR__;
function ormusLetter(name) {
  const part = ORMUS_SEPARATOR && name.includes(ORMUS_SEPARATOR)
    ? name.split(ORMUS_SEPARATOR).slice(1).join(ORMUS_SEPARATOR) : name;
  const chars = [...part.replace(/^[^\\p{L}\\p{N}]+/u, "")];
  return (chars[0] ?? [...part][0] ?? "?").toUpperCase();
}
function ormusTile(w, fill) {
  const o = ORMUS_SPACES[w.name] ?? {};
  const tile = h_flex().size(18).flex_none().rounded(5).items_center().justify_center();
  if (o.logo) {
    return tile.when(Boolean(o.bg), (el) => el.bg(o.bg))
      .child(image(`mods/ormus-spaces/logos/${o.logo}`).size(18 - 2 * (o.pad ?? 0)));
  }
  const bg = (o.accent && ORMUS_ACCENTS[o.accent]) || fill;
  return tile.bg(bg).text_size(10.5).font_semibold().text_color("__ON_ACCENT__")
    .child(o.letter ?? ormusLetter(w.name));
}
"""

NEEDS_TILES_JS = """// Ormus look (playbook-herdr-ormus-look, generated by src/space_tiles.py from spaces.json: do not edit).
import { image } from "gpui-kit";
import { h_flex } from "gpui-base";
import { shared, setShared, theme } from "herdr";
__MARK__
__SHARED__
// --- space colors (tests/test_tiles.py runs this part in node) ---
// Herdr's spaces mod gives each space a color from this palette, the least used one first, and keeps the
// choice in shared("space.colors"); a space that is gone loses its entry, the home space "~" gets none. The
// Flock view runs the same step, so a space has the same color whichever sidebar started first.
const SPACE_PALETTE = ["ansi6", "ansi3", "ansi4", "ansi5", "ansi2", "ansi1"];
function assignSpaceColors(old, list) {
  const ids = new Set(list.map((p) => p.id));
  const kept = Object.fromEntries(Object.entries(old ?? {}).filter(([id]) => ids.has(id)));
  let changed = Object.keys(kept).length !== Object.keys(old ?? {}).length;
  for (const p of list) {
    if (kept[p.id] || p.name === "~") continue;
    const uses = (c) => Object.values(kept).filter((v) => v === c).length;
    kept[p.id] = SPACE_PALETTE.reduce((best, c) => (uses(c) < uses(best) ? c : best));
    changed = true;
  }
  return { kept, changed };
}
// --- end of space colors ---
export function keepSpaceColors(list) {
  const { kept, changed } = assignSpaceColors(shared("space.colors"), list);
  if (changed) setShared("space.colors", kept);
}
// A space's tile: its logo, else its accent tile with its letter, on the space's color.
export function spaceTile(w) {
  const t = theme();
  const color = (shared("space.colors") ?? {})[w.id] ?? "ansi6";
  const fill = color.startsWith("#") ? color : (MARK[color] ?? t[color]);
  return ormusTile(w, fill);
}
"""


def mark_js() -> str:
    pairs = ", ".join(f'{k}: "{ACCENTS[v]}"' for k, v in MARK_TO_ACCENT.items())
    return f"const MARK = {{ {pairs} }};"


def tile_js(table: dict[str, dict], separator: str) -> str:
    """The JS every patched mod shares: the table and the tile."""
    return (
        TILE_JS.replace("__TABLE__", json.dumps(table, ensure_ascii=False, sort_keys=True))
        .replace("__ACCENTS__", json.dumps(ACCENTS, sort_keys=True))
        .replace("__SEPARATOR__", json.dumps(separator, ensure_ascii=False))
        .replace("__ON_ACCENT__", TILE_ON_ACCENT)
    )


_EDITS = [0]  # how many anchored edits have been made so far, for the install report


def counted(patch: Callable[[str], str], src: str) -> tuple[str, int]:
    """Run a patch function and say how many edits it made."""
    before = _EDITS[0]
    out = patch(src)
    return out, _EDITS[0] - before


def edit(text: str, old: str, new: str, what: str) -> str:
    """Replace `old` by `new`, which must appear exactly once, else stop and say what moved."""
    if text.count(old) != 1:
        raise SystemExit(
            f"the Herdr anchor for {what} is gone or not unique: Herdr changed this mod. "
            "Nothing was written. Update the anchor in src/space_tiles.py or src/pane_head.py "
            "(PLAYBOOK.md, 'When Herdr moves the code')."
        )
    _EDITS[0] += 1
    return text.replace(old, new)


def patch_spaces(src: str, shared_js: str) -> str:
    s = edit(src, GPUI_IMPORT, GPUI_IMPORT_IMAGE, "the gpui-kit import")
    s = edit(s, UPSTREAM_MARK, mark_js() + "\n" + shared_js, "the MARK table")
    return edit(s, SPACES_TILE, ".when(!tree, el => el.child(ormusTile(w, fill)))", "the space row tile")


def patch_picker(src: str, shared_js: str) -> str:
    s = edit(src, GPUI_IMPORT, GPUI_IMPORT_IMAGE, "the gpui-kit import")
    s = edit(s, UPSTREAM_MARK, mark_js() + "\n" + shared_js, "the MARK table")
    return edit(s, PICKER_TILE, ".child(ormusTile(r.w, spaceColor(t, r.w)))", "the picker's space header tile")


def needs_tiles_js(shared_js: str) -> str:
    """mods/ormus-needs/tiles.js: the same table and tile, for the Flock sidebar."""
    return NEEDS_TILES_JS.replace("__MARK__", mark_js()).replace("__SHARED__", shared_js.strip("\n"))


def mod_json(upstream_text: str, name: str, title: str, version: str) -> str:
    """Herdr's mod.json for the mod, with a new title and Herdr's own clone marker."""
    data = json.loads(upstream_text)
    data["title"] = title
    data["cloned_from"] = {"name": name, "version": version}
    return json.dumps(data, indent=2) + "\n"
